from __future__ import annotations

import copy
import hashlib
import json
import re
import uuid
import zipfile
from datetime import datetime, timezone
from pathlib import Path

import yaml

from .catalog import HEADER, parse_template, quote
from .domain import Project, RevisorError, atomic_write, confined, user_data_dir, validate_language, validate_translation

MANIFEST = ".renpy-revisor-manifest.json"


def render_files(project: Project) -> dict[str, bytes]:
    validate_language(project.language)
    files = {}
    changes = {}
    native_strings = set()
    for e in project.entries:
        validate_translation(e.source, e.target)
        if e.kind in ("dialogue", "string"):
            changes.setdefault(e.template, []).append(e)
            if e.kind == "string":
                native_strings.add(e.source)
    for name, text in project.templates.items():
        # Validate stored spans against a fresh parse before modifying code.
        parsed = {e.id: e for e in parse_template(name, text, project.template_language)}
        for e in changes.get(name, []):
            expected = parsed.get(e.id)
            if not expected or (e.source, e.start, e.end, e.block) != (expected.source, expected.start, expected.end, expected.block):
                raise RevisorError(f"O template de {name} foi alterado ou o projeto está corrompido.")
        for e in sorted(changes.get(name, []), key=lambda e: e.start, reverse=True):
            text = text[:e.start] + quote(e.target or e.source) + text[e.end:]
        text = re.sub(r"(?m)^(translate\s+)" + re.escape(project.template_language) + r"(\s+)",
                      lambda m: m[1] + project.language + m[2], text)
        files[(Path("revisor") / "native" / name).as_posix()] = ("# Generated by Ren'Py Translator & Revisor\n" + text).encode("utf-8")
    docs = copy.deepcopy(project.yaml_documents)
    extra_strings = {}
    # If YAML/native sources coincide, their chosen translations must agree.
    targets = {e.source: e.target or e.source for e in project.entries if e.kind == "string"}
    for e in project.entries:
        if e.kind != "yaml":
            continue
        target = e.target or e.source
        if e.source in targets and targets[e.source] != target:
            raise RevisorError(f"Traduções conflitantes para a string YAML {e.source[:70]!r}. Use o mesmo texto nas ocorrências.")
        targets[e.source] = target
        if e.source not in native_strings:
            extra_strings[e.source] = target
        try:
            if not e.yaml_path:
                docs[e.file] = target
            else:
                node = docs[e.file]
                for key in e.yaml_path[:-1]:
                    node = node[key]
                node[e.yaml_path[-1]] = target
        except (KeyError, IndexError, TypeError) as exc:
            raise RevisorError(f"Caminho YAML inválido em {e.file}.") from exc
    for name, doc in docs.items():
        if name.startswith("revisor/"):
            raise RevisorError("O YAML usa a pasta reservada revisor. Abra o jogo novamente sem incluir YAML para exportar a tradução nativa.")
        files[name] = yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=120).encode("utf-8")
    if extra_strings:
        text = f"# YAML strings — Ren'Py Translator & Revisor\ntranslate {project.language} strings:\n\n"
        for source, target in extra_strings.items():
            text += f"    old {quote(source)}\n    new {quote(target)}\n\n"
        files["revisor/yaml_strings.rpy"] = text.encode("utf-8")
    if project.activate_language:
        files["revisor/00_language.rpy"] = ("# Generated by Ren'Py Translator & Revisor\n"
                                              f"init 10 python:\n    config.language = {quote(project.language)}\n").encode("utf-8")
    return files


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def check_conflicts(root: Path, files: dict[str, bytes], owned: dict, language: str):
    new_blocks = set()
    new_strings = set()
    for name, data in files.items():
        if name.endswith(".rpy"):
            text = data.decode("utf-8")
            new_blocks.update(m[2] for line in text.splitlines() if (m := HEADER.match(line)) and m[2] != "strings")
            new_strings.update(e.source for e in parse_template(name, text, language) if e.kind == "string")
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        name = path.relative_to(root).as_posix()
        if name in owned or (path.suffix == ".rpyc" and path.with_suffix(".rpy").relative_to(root).as_posix() in owned):
            continue
        if path.suffix == ".rpyc" and not path.with_suffix(".rpy").is_file():
            raise RevisorError(f"Há traduções compiladas sem fonte em {name}. Escolha um novo identificador de idioma para evitar conflitos.")
        if path.suffix != ".rpy":
            continue
        text = path.read_text("utf-8-sig")
        blocks = {m[2] for line in text.splitlines() if (m := HEADER.match(line)) and m[1] == language and m[2] != "strings"}
        strings = {e.source for e in parse_template(name, text, language) if e.kind == "string"}
        if blocks & new_blocks or strings & new_strings:
            raise RevisorError(f"Já existe tradução conflitante em {name}. Escolha um novo idioma Ren'Py ou remova essa tradução após fazer backup.")


def export_project(project: Project) -> tuple[Path, int, Path | None]:
    game = Path(project.game_root).resolve() / "game"
    if not game.is_dir():
        raise RevisorError("A pasta game não existe. Abra o projeto no computador onde o jogo está instalado.")
    validate_language(project.language)
    tl = game / "tl"
    if not tl.resolve().is_relative_to(game.resolve()):
        raise RevisorError("game/tl aponta para fora da pasta game. Use uma pasta de tradução regular.")
    root = confined(tl, project.language)
    files = render_files(project)
    manifest = confined(root, MANIFEST)
    owned = {}
    if manifest.exists():
        try:
            previous = json.loads(manifest.read_text("utf-8"))
            if previous["generator"] != "renpy-revisor" or previous["language"] != project.language:
                raise ValueError("Manifesto de outro projeto")
            owned = previous["files"]
            if not isinstance(owned, dict):
                raise ValueError("Lista de arquivos inválida")
        except (ValueError, KeyError, TypeError) as exc:
            raise RevisorError(f"Manifesto de exportação inválido: {exc}") from exc
    for name, expected in owned.items():
        path = confined(root, name)
        if path.is_file() and digest(path.read_bytes()) != expected:
            raise RevisorError(f"{name} foi editado fora do revisor. Faça backup e escolha outro idioma para preservar a edição.")
    for name in files:
        target = confined(root, name)
        if target.exists() and name not in owned:
            raise RevisorError(f"A exportação sobrescreveria um arquivo existente: {name}. Escolha outro idioma.")
    if project.activate_language and tl.exists():
        others = [p for p in tl.glob("*/revisor/00_language.rpy") if p.parent.parent != root]
        if others:
            raise RevisorError("Outra tradução do revisor já ativa um idioma ao iniciar. Desative essa opção no projeto anterior e salve, ou desmarque-a neste projeto.")
    if root.exists():
        check_conflicts(root, files, owned, project.language)
    affected = {confined(root, name) for name in set(owned) | set(files)} | {manifest}
    # Remove only compiled siblings of files this application owns.
    affected |= {confined(root, name).with_suffix(".rpyc") for name in owned if name.endswith(".rpy")}
    before = {p: p.read_bytes() if p.is_file() else None for p in affected}
    backup = None
    if any(value is not None for value in before.values()):
        folder = user_data_dir() / "backups"
        folder.mkdir(exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
        backup = folder / f"{game.parent.name}-{project.language}-{stamp}-{uuid.uuid4().hex[:6]}.zip"
        with zipfile.ZipFile(backup, "w", zipfile.ZIP_DEFLATED) as z:
            for path, value in before.items():
                if value is not None:
                    z.writestr(path.relative_to(root).as_posix(), value)
    try:
        for name, data in files.items():
            atomic_write(confined(root, name), data)
        for name in owned:
            if name not in files:
                confined(root, name).unlink(missing_ok=True)
            if name.endswith(".rpy"):
                confined(root, name).with_suffix(".rpyc").unlink(missing_ok=True)
        info = {"generator": "renpy-revisor", "language": project.language, "files": {name: digest(data) for name, data in files.items()}}
        atomic_write(manifest, json.dumps(info, indent=2, ensure_ascii=False).encode("utf-8"))
    except OSError as exc:
        restore_errors = []
        for path, data in before.items():
            try:
                if data is None:
                    path.unlink(missing_ok=True)
                else:
                    atomic_write(path, data)
            except OSError as rollback_exc:
                restore_errors.append(f"{path.name}: {rollback_exc}")
        if restore_errors:
            raise RevisorError(f"Falha ao salvar ({exc}) e restauração incompleta. Backup: {backup or 'nenhuma versão anterior'}.\n" + "\n".join(restore_errors)) from exc
        raise RevisorError(f"Não foi possível salvar no jogo: {exc}. As versões anteriores foram restauradas.") from exc
    return root, len(files), backup
